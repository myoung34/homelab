def test_gcode_findings_against_real_config() -> None:
    cfg = kc.parse(fixture("enderbig.cfg"))
    rep = gcode.inspect(PRUSA_GCODE, cfg)
    codes = {f["code"]: f for f in rep.findings}
    assert "LOAD" in codes["bed_mesh_bad_param"]["message"]
    assert "BED_MESH_PROFILE LOAD=default" in codes["bed_mesh_bad_param"]["message"]
    assert codes["gcode_flavor"]["failure_class"] == "SLICER.incorrect_profile"
    assert rep.marlin_only == {"M201": 1, "M203": 1}
    assert rep.unknown_commands == {"PRINT_END": 1}
    assert codes["out_of_range"]["failure_class"] == "MOTION.out_of_range"  # X400 > 353
    assert "accel_above_limit" in codes
    assert rep.slicer and rep.slicer.startswith("generated by PrusaSlicer")
    assert rep.first_extrusion_line is not None


def test_homing_twice_via_macro_is_explained() -> None:
    cfg = kc.parse(fixture("enderbig.cfg") + "\n[gcode_macro PRINT_START]\ngcode:\n  G28\n  BED_MESH_CALIBRATE\n")
    # place the macro above SAVE_CONFIG so it parses as a user section
    text = fixture("enderbig.cfg").replace(
        "[pause_resume]", "[gcode_macro PRINT_START]\ngcode:\n  G28\n\n[pause_resume]"
    )
    cfg = kc.parse(text)
    rep = gcode.inspect("G28\nPRINT_START\nM109 S200\nG1 X10 Y10 E1\n", cfg)
    msgs = {f["code"]: f["message"] for f in rep.findings}
    assert "multiple_homing" in msgs and "PRINT_START (macro contains G28)" in msgs["multiple_homing"]


def test_extrude_before_wait_and_no_home() -> None:
    rep = gcode.inspect("M104 S200\nG1 X10 Y10 E2\nM109 S200\n")
    codes = {f["code"] for f in rep.findings}
    assert {"extrude_before_wait", "no_homing"} <= codes


