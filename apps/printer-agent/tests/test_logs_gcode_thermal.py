def test_thermal_stable() -> None:
    temps = [20 + i * 2 for i in range(95)] + [210 + (0.3 if i % 2 else -0.3) for i in range(100)]
    a = thermal.analyse("extruder", temps, [210.0] * len(temps), [0.4] * len(temps))
    assert a.verdict == "stable", a.findings


def test_thermal_oscillation_and_jumps() -> None:
    temps = [210 + (4 if (i // 5) % 2 else -4) for i in range(200)]
    a = thermal.analyse("extruder", temps, [210.0] * 200)
    assert a.verdict == "unstable" and any("oscillating" in f for f in a.findings)
    temps = [21.0] * 50 + [45.0] + [21.0] * 50
    a = thermal.analyse("extruder", temps, [0.0] * 101)
    assert a.verdict == "fault_suspected"


def test_thermal_not_heating_at_full_power() -> None:
    temps = [25.0] * 120
    a = thermal.analyse("extruder", temps, [200.0] * 120, [1.0] * 120)
    assert a.verdict == "fault_suspected" and "saturated" in a.findings[0]


def test_runaway_shape() -> None:
    trace = [{"t": i, "temp": 210 - i * 0.5, "target": 210.0, "pwm": 1.0} for i in range(60)]
    assert thermal.runaway_shape(trace)["shape"] == "falling_at_full_power"
    trace = [{"t": i, "temp": 210.0 + (30 if i == 30 else 0), "target": 210.0, "pwm": 0.4} for i in range(60)]
    assert thermal.runaway_shape(trace)["shape"] == "sensor_jumps"
