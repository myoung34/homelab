# ------------------------------------------------------------------ klippy.log


def test_sessions_anchor_wall_clock_and_classify_shutdown() -> None:
    text = klippy_log(
        fixture("enderbig.cfg"),
        stats=stats_series(20, start=10),
        events=[
            (25.0, "Transition to shutdown state: Lost communication with MCU 'mcu'"),
        ],
    )
    log = kl.parse(text, TAX)
    assert len(log.sessions) == 1
    s = log.sessions[0]
    assert s.version == "v0.12.0-450-gabcdef"
    assert s.start_wall == T0 and s.anchored_by == "start_line"
    assert len(s.stats) == 20
    assert s.stats[0].groups["extruder"]["temp"] == 21.0
    assert s.stats[0].groups["_"]["sysload"] == 0.3  # host-wide keys normalized
    sd = s.shutdown
    assert sd is not None and sd.failure_class == "FIRMWARE.mcu_disconnect"
    # Placed at the last Stats eventtime before it, flagged approximate.
    assert sd.wall is not None and abs(sd.wall - (T0 + 25.0 - 1)) < 1.01 and sd.approximate
    assert kc.parse(s.config_text or "").value("bltouch", "z_offset") == "3.420"


def test_restart_starts_new_session_and_gcode_dump() -> None:
    text = klippy_log(
        fixture("enderbig.cfg"),
        events=[(5, "Heater extruder not heating at expected rate")],
        gcode_dump=["G1 X1 E1", "G1 X2 E1"],
    )
    text += f"Start printer at Thu Oct  1 13:00:00 2026 ({T0 + 4000:.1f} {MONO0 + 4000:.1f})\n"
    log = kl.parse(text, TAX)
    assert len(log.sessions) == 2
    assert [g for _, g in log.sessions[0].gcode_dump] == ["G1 X1 E1", "G1 X2 E1"]
    assert log.sessions[1].start_wall == T0 + 4000


def test_tail_without_start_line_uses_live_offset() -> None:
    text = "Stats 5000.0: gcodein=0  extruder: target=0 temp=21.0 pwm=0.000\nProbe triggered prior to movement\n"
    log = kl.parse(text, TAX, truncated=True, live_offset=T0)
    s = log.sessions[0]
    assert s.anchored_by == "live_offset"
    ev = s.events[0]
    assert ev.failure_class == "PROBE.probe_triggering_too_early"
    assert ev.wall == T0 + 5000.0


def test_link_trend_and_heater_trace() -> None:
    text = klippy_log(
        fixture("enderbig.cfg"), stats=stats_series(60, retransmit_fn=lambda i: i * 10, extruder=(200.0, 200.0, 0.5))
    )
    s = kl.parse(text, TAX).sessions[0]
    trend = kl.link_trend(s)
